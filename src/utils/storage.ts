export function saveUserProfile(profile: UserProfile): void {
  localStorage.setItem(LOCAL_PROFILE_KEY, JSON.stringify(profile));
}

export function getOrCreateLocalUuid(): string {
  return getOrCreateUserProfile().uuid;
}

export function getLocalCallsign(): string {
  return getOrCreateUserProfile().callsign;
}

export function setLocalCallsign(callsign: string): void {
  const p = getOrCreateUserProfile();
  p.callsign = callsign;
  saveUserProfile(p);
}

